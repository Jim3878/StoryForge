// Copies the flow graph canvas (StoryForge's own graph-editor.js on top of the vendored LiteGraph) from
// StoryForge.Web's wwwroot into assets/, which ships inside the package, and writes src/assets-version.ts
// with a content hash: the AFFiNE fork loads the files as /sf-assets/<file>?v=<hash>, so a new copy is a new
// URL and the server's hours-long cache cannot serve an old canvas. Runs as part of `npm run build`;
// assets/ and src/assets-version.ts are generated and not committed.
import { createHash } from "crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const webRoot = path.resolve(root, "..", "src/StoryForge.Web/wwwroot");
const assets = path.join(root, "assets");
mkdirSync(assets, { recursive: true });

// Same files and hash order as the old copy-schema-to-affine.mjs, so the version stays comparable.
const files = [
  ["lib/litegraph/litegraph.min.js", "litegraph.min.js"],
  ["lib/litegraph/litegraph.css", "litegraph.css"],
  ["js/graph-editor.js", "graph-editor.js"],
];
const hash = createHash("sha1");
for (const [from, to] of files) {
  const bytes = readFileSync(path.join(webRoot, from));
  hash.update(bytes);
  const target = path.join(assets, to);
  if (!existsSync(target) || !readFileSync(target).equals(bytes)) writeFileSync(target, bytes);
}
const version = hash.digest("hex").slice(0, 10);
const out = path.join(root, "src", "assets-version.ts");
const text =
  "// GENERATED by scripts/copy-assets.mjs. Do not edit.\n" +
  `export const SF_ASSETS_VERSION = "${version}";\n` +
  `export const SF_ASSET_FILES = ${JSON.stringify(files.map(([, to]) => to))} as const;\n`;
if (!existsSync(out) || readFileSync(out, "utf8") !== text) writeFileSync(out, text);
